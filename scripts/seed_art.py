def generate():
    for name, rows in ART.items():
        folder = ROOT / ("programs" if name in ("HANGMAN", "TICTACTO", "CUBE3D") else "categories") / name
        folder.mkdir(parents=True, exist_ok=True)
        color = {"GAMES": 3, "UTILS": 7, "DEMOS": 14, "LAB": 13, "HANGMAN": 7, "TICTACTO": 3, "CUBE3D": 14}[name]
        for frame in range(1, 3 if name in ("HANGMAN", "TICTACTO", "CUBE3D") else 2):
            image = Image.new("RGB", (16, 16), RGB[0])
            for y, row in enumerate(rows):
                for x, pixel in enumerate(row):
                    if pixel == "#":
                        image.putpixel((x, y), RGB[color if frame == 1 else 1])
            image.save(folder / ("icon.png" if frame == 1 else f"icon-{frame}.png"))


if __name__ == "__main__":
    generate()
