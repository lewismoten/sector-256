; Display leading decimal digits of pi and its circumference formula.
.include "api.inc"
.cpu "6502"
*=$c000
p=$20
 lda #>t
 sta p+1
 jsr CLEAR
 ldx #<t
 stx p
 ldy #0
l:lda (p),y
 beq d
 jsr PUTCHAR
 iny
 bne l
d:jsr WAITKEY
 jmp d
t:.text "PI",13,13,"3.141592653589793",13,13,"CIRCUMFERENCE = 2 PI R",13,0
