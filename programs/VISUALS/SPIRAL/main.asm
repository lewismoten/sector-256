; Animated PETSCII glyphs trace a fixed path toward the center.
.include "api.inc"
.cpu "6502"
*=$c000
p=$02
 jsr CLEAR
loop:
 jsr CLEAR
 ldx #0
plot:
 lda lo,x
 sta $20
 lda hi,x
 sta $21
 txa
 clc
 adc p
 and #7
 clc
 adc #42
 ldy #0
 sta ($20),y
 inx
 cpx #16
 bne plot
 inc p
 jsr POLLKEY
 jmp loop
